"""Provisional B-side contract, deliberately separate from C's eventual schemas.

Only the standard library is required. Adapters may construct these dataclasses
from C's validated Pydantic models. Evidence annotations are generated by B's
source_review stage or trusted B review records, never by C's extraction status.
"""

from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any, Literal

from .field_catalog import MANDATORY_FIELDS

FieldStatus = Literal["verified", "pending", "conflict"]
REQUIRED_FIELDS = MANDATORY_FIELDS


@dataclass(frozen=True)
class Evidence:
    id: str
    field: str
    value: str
    url: str
    quote: str
    edition: str
    source_type: str = "unknown"  # official / school / third_party / unknown
    source_verified: bool = False
    support: str = "unknown"  # supported / unsupported / unknown
    reviewed_by: str | None = None
    retrieved_at: str | None = None
    scope: str = "global"  # e.g. global vs campus:<school>; never mix deadlines
    value_kind: str = "value"  # not_applicable needs a directly supported statement
    review_reasons: tuple[str, ...] = ()  # recomputed by B; never a C trust assertion
    source_id: str | None = None  # C's explicit snapshot identity, not a trust flag


@dataclass
class Competition:
    id: str
    name: str
    edition: str
    fields: dict[str, Any] = field(default_factory=dict)
    evidence: list[Evidence] = field(default_factory=list)
    scope: str = "global"
    field_scopes: dict[str, str] = field(default_factory=dict)


@dataclass(frozen=True)
class VerificationPolicy:
    required_fields: tuple[str, ...] = REQUIRED_FIELDS
    accepted_source_types: tuple[str, ...] = ("official",)
    conflict_source_types: tuple[str, ...] = ("official", "school")
    promoted_fields: tuple[str, ...] = ()
    requirement_reasons: dict[str, tuple[str, ...]] = field(default_factory=dict)
    inspect_optional: bool = True
    school_accepted_fields: tuple[str, ...] = (
        "campus_deadline", "institutional_requirements", "school_recognition", "contacts",
    )

    def __post_init__(self) -> None:
        if not self.required_fields or len(set(self.required_fields)) != len(self.required_fields):
            raise ValueError("required_fields must be nonempty and unique")
        if not self.accepted_source_types:
            raise ValueError("accepted_source_types must not be empty")
        if any(name not in self.required_fields for name in self.promoted_fields):
            raise ValueError("promoted_fields must be required")


@dataclass
class FieldCheck:
    field: str
    status: FieldStatus
    original_value: Any
    verified_value: str | None = None
    reasons: list[str] = field(default_factory=list)
    evidence_ids: list[str] = field(default_factory=list)
    conflicting_values: list[str] = field(default_factory=list)
    rejected_evidence: dict[str, list[str]] = field(default_factory=dict)
    required: bool = True
    requirement_reasons: list[str] = field(default_factory=list)
    value_kind: str | None = None
    confirmed_statement: str | None = None
    scope: str = "global"
    next_action: str = "search"
    action_reason: str = "缺少可靠证据，需要补查。"
    source_urls: list[str] = field(default_factory=list)


@dataclass
class VerificationResult:
    competition_id: str
    status: FieldStatus
    fields: dict[str, FieldCheck]
    missing_fields: list[str]
    unresolved_fields: list[str]
    coverage: float
    required_fields: list[str] = field(default_factory=list)
    promoted_fields: list[str] = field(default_factory=list)
    optional_unresolved_fields: list[str] = field(default_factory=list)
    optional_conflict_fields: list[str] = field(default_factory=list)
    unrecognized_fields: list[str] = field(default_factory=list)
    verified_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat(), compare=False)
    consistency_issues: list[dict[str, Any]] = field(default_factory=list)

    @property
    def verified_fields(self) -> dict[str, str]:
        return {
            name: check.verified_value
            for name, check in self.fields.items()
            if check.status == "verified" and check.verified_value is not None
        }

    def to_dict(self) -> dict[str, Any]:
        from .next_steps import action_items
        return {**asdict(self), "verified_fields": self.verified_fields,
                "not_applicable_fields": {
                    name: check.confirmed_statement for name, check in self.fields.items()
                    if check.status == "verified" and check.value_kind == "not_applicable"
                },
                "status_scope": "required_fields_only", "action_items": action_items(self.fields)}


@dataclass(frozen=True)
class SearchQuery:
    competition_id: str
    field: str
    text: str
    reason: str
    scope: str = "global"


@dataclass
class SearchBatch:
    """A's search + C's extraction adapter returns new evidence only.

    The controller does not replace whole candidates or rewrite original values.
    One callback is one counted search call. cost is measured in the single cost
    unit agreed with A. None means unknown, NOT free.
    """

    evidence: list[Evidence] = field(default_factory=list)
    cost: float | None = None
    error: str | None = None


@dataclass(frozen=True)
class SearchBudget:
    max_rounds: int = 2
    max_calls: int = 6
    max_queries_per_round: int = 3
    max_cost: float | None = None
    max_no_progress_rounds: int = 1

    def __post_init__(self) -> None:
        from math import isfinite

        for name in ("max_rounds", "max_calls"):
            value = getattr(self, name)
            if type(value) is not int or value < 0:
                raise ValueError(f"{name} must be a nonnegative integer")
        for name in ("max_queries_per_round", "max_no_progress_rounds"):
            value = getattr(self, name)
            if type(value) is not int or value < 1:
                raise ValueError(f"{name} must be a positive integer")
        if self.max_cost is not None and (
            isinstance(self.max_cost, bool)
            or not isinstance(self.max_cost, (int, float))
            or not isfinite(self.max_cost)
            or self.max_cost < 0
        ):
            raise ValueError("max_cost must be a finite nonnegative number")


@dataclass
class SearchEvent:
    round: int
    query: SearchQuery
    before_status: str
    after_status: str
    new_evidence_count: int
    new_valid_evidence_count: int
    cost: float | None
    elapsed_seconds: float
    error: str | None = None
    newly_verified_fields: list[str] = field(default_factory=list)
    coverage_before: float = 0.0
    coverage_after: float = 0.0


@dataclass
class AdaptiveResult:
    competition: Competition
    verification: VerificationResult
    stop_reason: str
    rounds: int
    calls: int
    known_cost: float
    cost_complete: bool
    events: list[SearchEvent]

    def to_dict(self) -> dict[str, Any]:
        result = asdict(self)
        result["verification"] = self.verification.to_dict()
        return result
